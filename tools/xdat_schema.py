"""Generates crates/ue2/src/xdat_schema.rs from acmi's xdat_editor_schema
(Groovy, chronicle folder such as etoa5): the field lists of every
@DefaultIO class (read in declaration order) and which enums are written as
strings. Classes with a hand-written read() are implemented in xdat.rs.

usage: python tools/xdat_schema.py <schema>/src/main/groovy/etoa5 > crates/ue2/src/xdat_schema.rs
"""
import os
import re
import sys

src = sys.argv[1]
classes = {}      # name -> (super, defaultio, [(kind, field, arg)])
string_enums = set()
all_enums = set()

FIELD = re.compile(r'^\s*(?:final\s+)?([A-Za-z_][\w<>, ]*?)\s+([a-z_]\w*)\s*(=.*)?$')


def parse(text):
    lines = text.split('\n')
    stack = []  # (class name, defaultio, depth)
    depth = 0
    pending_defaultio = False
    pending_annos = []
    for raw in lines:
        line = raw.split('//')[0].rstrip()
        s = line.strip()
        if s.startswith('@'):
            if s.startswith('@DefaultIO'):
                pending_defaultio = True
            pending_annos.append(s)
            # annotations on the same line as a field: "@Tex String file"
            rest = re.sub(r'^(@\w+(\([^)]*\))?\s*)+', '', s)
            if rest == s or not rest:
                continue
            s = rest
        m = re.match(r'^(?:(?:public|static|abstract|final)\s+)*(class|enum)\s+(\w+)(.*)$', s)
        if m:
            kind, name, tail = m.groups()
            if kind == 'enum':
                all_enums.add(name)
                if 'StringValue' in tail:
                    string_enums.add(name)
            else:
                sup = re.search(r'extends\s+(\w+)', tail)
                classes[name] = [sup.group(1) if sup else None, pending_defaultio, []]
                stack.append((name, depth))
            pending_defaultio = False
            pending_annos = []
        elif stack and depth == stack[-1][1] + 1 and s and not s.startswith(('@', '}', 'static', 'enum', 'transient')) and '(' not in s.split('=')[0]:
            fm = FIELD.match(s)
            if fm and not s.startswith('return'):
                typ, name = fm.group(1).strip(), fm.group(2)
                if typ not in ('def',) and not typ.startswith('static'):
                    anno = ' '.join(pending_annos)
                    classes[stack[-1][0]][2].append((typ, name, anno))
            pending_annos = []
        else:
            if not s.startswith('@'):
                pending_annos = []
        depth += line.count('{') - line.count('}')
        while stack and depth <= stack[-1][1]:
            stack.pop()


for f in sorted(os.listdir(src)):
    if f.endswith('.groovy'):
        parse(open(os.path.join(src, f), encoding='utf-8').read())


def kind(typ, anno):
    if typ == 'int':
        return 'Int', None
    if typ in ('boolean', 'Boolean'):
        return 'Bool', None
    if typ == 'float':
        return 'Float', None
    if typ == 'String':
        return 'Str', None
    if typ == 'Color':
        return ('Rgba', None) if '@RGBA' in anno else ('Color', None)
    m = re.match(r'List<(\w+)>', typ)
    if m:
        return 'List', m.group(1)
    if typ in all_enums:
        return ('EnumStr', None) if typ in string_enums else ('EnumInt', None)
    return 'Entity', typ


# Differences of this Classic client from the Salvation schema, found by
# reading its interface.xdat: fields that are absent.
REMOVE = {
    'RadioButton': ['text'],
}
for cls, names in REMOVE.items():
    classes[cls][2] = [f for f in classes[cls][2] if f[1] not in names]

print('// Generated by tools/xdat_schema.py from acmi/xdat_editor_schema; do not edit.')
print('use crate::xdat::Kind;')
print()
print('/// (class, super class, fields) of the @DefaultIO classes.')
print('pub static CLASSES: &[(&str, Option<&str>, &[(&str, Kind)])] = &[')
for name, (sup, dio, fields) in sorted(classes.items()):
    # Empty controls (NameCtrl, Radar...) are plain DefaultProperty.
    if not dio and not (sup == 'DefaultProperty' and not fields):
        continue
    items = []
    for typ, fname, anno in fields:
        k, arg = kind(typ, anno)
        items.append(f'("{fname}", Kind::{k}' + (f'("{arg}")' if arg else '') + ')')
    sup_s = f'Some("{sup}")' if sup else 'None'
    print(f'    ("{name}", {sup_s}, &[{", ".join(items)}]),')
print('];')
